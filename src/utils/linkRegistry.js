/**
 * Resolves curated metadata for WhatsApp and Telephone contacts
 */
export function getContactPreview(url) {
  if (!url) return null;

  // WhatsApp
  if (url.includes('wa.me') || url.includes('api.whatsapp.com')) {
    const phoneMatch = url.match(/(?:\/|\?phone=)([0-9]{10,13})/);
    const phone = phoneMatch ? phoneMatch[1] : '';
    return {
      url,
      canonicalUrl: url,
      domain: 'wa.me',
      siteName: 'WhatsApp Messenger',
      title: 'WhatsApp Direct Hotline',
      titleMl: 'വാട്സാപ്പ് ഡയറക്ട് ഹോട്ട്ലൈൻ',
      description: `Connect directly with verified ADSA Canteen Committee representatives${phone ? ` (+${phone})` : ''} on WhatsApp for instant assistance.`,
      descriptionMl: 'കാന്റീൻ കമ്മിറ്റി ഭാരവാഹികളുമായി വാട്സാപ്പിൽ നേരിട്ട് ബന്ധപ്പെട്ട് സംശയങ്ങൾ ദൂരീകരിക്കുക.',
      image: null,
      favicon: 'https://static.whatsapp.net/rsrc.php/v3/yP/r/rNqcCO-XYgw.png',
      mediaType: 'whatsapp',
      trustStatus: 'verified_comm',
      gradient: 'from-green-600 via-emerald-600 to-green-700',
      badgeText: 'Instant Messaging',
      badgeTextMl: 'തത്സമയ സന്ദേശം',
    };
  }

  // Telephone Call Desk
  if (url.startsWith('tel:')) {
    const rawNumber = url.replace('tel:', '');
    return {
      url,
      canonicalUrl: url,
      domain: 'tel',
      siteName: 'ADSA Telephony Desk',
      title: `Call Operations Desk (${rawNumber})`,
      titleMl: `കാമ്പസ് കോൾ ഡെസ്ക് (${rawNumber})`,
      description: 'Official ADSA mess management telephone support. Available daily from 06:00 AM to 02:00 PM and 06:00 PM to 09:30 PM IST.',
      descriptionMl: 'എ.ഡി.എസ്.എ കാന്റീൻ പ്രവർത്തനങ്ങളുമായി ബന്ധപ്പെട്ട അടിയന്തിര ഫോൺ സഹായം.',
      image: null,
      favicon: null,
      mediaType: 'phone',
      trustStatus: 'verified_internal',
      gradient: 'from-teal-600 via-emerald-600 to-teal-800',
      badgeText: 'Voice Desk',
      badgeTextMl: 'ഫോൺ ഹെൽപ്പ്‌ലൈൻ',
    };
  }

  return null;
}
